export function getInstrumentHand(
  instrumentId: DrumInstrumentId,
  handedness: Handedness,
  invertHands: boolean = false
): Hand {
  const isFloorOrBass = instrumentId === 'bass' || instrumentId === 'floor_tom';

  let assignedHand: Hand;
  if (handedness === 'RIGHT_HANDED') {
    assignedHand = isFloorOrBass ? 'RIGHT' : 'LEFT';
  } else {
    assignedHand = isFloorOrBass ? 'LEFT' : 'RIGHT';
  }

  if (invertHands) {
    assignedHand = assignedHand === 'RIGHT' ? 'LEFT' : 'RIGHT';
  }

  return assignedHand;
}

